def feature_collection(rows):
    return {"type":"FeatureCollection", "features":[{"type":"Feature","id":r["id"],
        "properties":{"id":r["id"],"class":r["class"]},"geometry":mapping(r["geometry"])} for r in rows]}

def cell_polygon(x0,y0,x1,y1, segments=4):
    xy=[]
    for a,b in [((x0,y0),(x1,y0)),((x1,y0),(x1,y1)),
                ((x1,y1),(x0,y1)),((x0,y1),(x0,y0))]:
        for j in range(segments):
            t=j/segments
            xy.append((round(a[0]+t*(b[0]-a[0]),12), round(a[1]+t*(b[1]-a[1]),12)))
    xy.append(xy[0])
    return Polygon(xy)

def grid(n):
    nx=int(math.sqrt(n))
    while n%nx: nx-=1
    ny=n//nx
    x0,y0,x1,y1=BOUNDS
    xs=[round(x0+(x1-x0)*i/nx,12) for i in range(nx+1)]
    ys=[round(y0+(y1-y0)*j/ny,12) for j in range(ny+1)]
    # Non-collinear zigzag vertices avoid conflating shared-arc storage with
    # a library's removal of exactly collinear intermediate vertices.
    wave=[0,1,-1,1,0]
    amp_x=(x1-x0)/nx*0.06; amp_y=(y1-y0)/ny*0.06
    horizontal={}
    vertical={}
    for j in range(ny+1):
        for i in range(nx):
            sign=1 if (i+j)%2==0 else -1
            horizontal[i,j]=[(round(xs[i]+(xs[i+1]-xs[i])*k/4,12),
                round(ys[j]+(0 if j in (0,ny) else sign*amp_y*wave[k]),12)) for k in range(5)]
    for i in range(nx+1):
        for j in range(ny):
            sign=1 if (i+j)%2==0 else -1
            vertical[i,j]=[(round(xs[i]+(0 if i in (0,nx) else sign*amp_x*wave[k]),12),
                round(ys[j]+(ys[j+1]-ys[j])*k/4,12)) for k in range(5)]
    rows=[]
    for j in range(ny):
        for i in range(nx):
            edges=[horizontal[i,j],vertical[i+1,j],list(reversed(horizontal[i,j+1])),list(reversed(vertical[i,j]))]
            coords=[xy for edge in edges for xy in edge[:-1]];coords.append(coords[0])
            rows.append({"id":j*nx+i+1,"class":(i+j)%5,"geometry":Polygon(coords)})
    return rows, {"n":n,"nx":nx,"ny":ny,"bounds_crs84":list(BOUNDS),"ring_coordinate_pairs":17,
                 "coordinate_decimal_places":12,"edge_segments":4,
                 "interior_edge_zigzag_amplitude_fraction":0.06,"outer_boundary":"rectangle"}

def topology(rows):
    return topojson.Topology(feature_collection(rows),prequantize=False,topoquantize=False,
        presimplify=False,toposimplify=False,topology=True,
        winding_order="CCW_CW",object_name="cells").to_dict()

def decode_topology(data):
    """Small Polygon-only decoder implementing TopoJSON arcs and optional transform.

    Deliberately supports only the schema generated by this experiment.
    It is not a general replacement for a production TopoJSON decoder.
    """
    if data.get("type")!="Topology": raise ValueError("Expected Topology")
    arcs=[]
    for a in data["arcs"]:
        if "transform" in data:
            sc=data["transform"]["scale"];tr=data["transform"]["translate"]
            x=y=0;coords=[]
            for dx,dy in a:
                x+=dx;y+=dy
                coords.append((x*sc[0]+tr[0], y*sc[1]+tr[1]))
        else: coords=[tuple(p) for p in a]
        arcs.append(coords)
    out=[]
    for f in data["objects"]["cells"]["geometries"]:
        if f["type"]!="Polygon": raise ValueError("Experiment expects Polygon")
        rings=[]
        for ring in f["arcs"]:
            coords=[]
            for ref in ring:
                a=arcs[ref] if ref>=0 else list(reversed(arcs[~ref]))
                coords.extend(a if not coords else a[1:])
            if coords and coords[0]!=coords[-1]:coords.append(coords[0])
            rings.append(coords)
        p=f["properties"]
        out.append({"id":int(p["id"]),"class":int(p["class"]),
                    "geometry":Polygon(rings[0],rings[1:])})
    return out

def write_kml(path, rows):
    def node(parent,tag,text=None,**attrs):
        v=ET.SubElement(parent,ET.QName(KNS,tag),**attrs)
        if text is not None:v.text=str(text)
        return v
    root=ET.Element(ET.QName(KNS,"kml"),nsmap={None:KNS})
    doc=node(root,"Document")
    schema=node(doc,"Schema",id="cell_schema",name="cell_schema")
    node(schema,"SimpleField",name="id",type="int")
    node(schema,"SimpleField",name="class",type="int")
    for r in rows:
        pm=node(doc,"Placemark",id="cell_"+str(r["id"]))
        ed=node(pm,"ExtendedData");sd=node(ed,"SchemaData",schemaUrl="#cell_schema")
        node(sd,"SimpleData",r["id"],name="id");node(sd,"SimpleData",r["class"],name="class")
        pg=node(pm,"Polygon");node(pg,"altitudeMode","clampToGround")
        lr=node(node(pg,"outerBoundaryIs"),"LinearRing")
        node(lr,"coordinates"," ".join(f"{float(x)!r},{float(y)!r}" for x,y in r["geometry"].exterior.coords))
    Path(path).write_bytes(ET.tostring(root,encoding="UTF-8",xml_declaration=True,pretty_print=False))

def read_kml(path):
    root=ET.parse(str(path));ns={"k":KNS};rows=[]
    for pm in root.findall(".//k:Placemark",ns):
        props={v.get("name"):int(v.text) for v in pm.findall("k:ExtendedData/k:SchemaData/k:SimpleData",ns)}
        txt=pm.find("k:Polygon/k:outerBoundaryIs/k:LinearRing/k:coordinates",ns).text
        coords=[tuple(float(v) for v in item.split(",")[:2]) for item in txt.split()]
        rows.append({"id":props["id"],"class":props["class"],"geometry":Polygon(coords)})
    return rows

def write_profile(path, rows, profile):
    if profile=="GeoJSON":Path(path).write_text(js(feature_collection(rows)),encoding="utf-8")
    elif profile=="TopoJSON":Path(path).write_text(js(topology(rows)),encoding="utf-8")
    elif profile=="KML":write_kml(path,rows)
    else:
        frame=gpd.GeoDataFrame({"id":[r["id"] for r in rows],"class":[r["class"] for r in rows]},
            geometry=[r["geometry"] for r in rows],crs="OGC:CRS84")
        frame.to_parquet(path,index=False,geometry_encoding="WKB",schema_version="1.1.0",
            compression=None if profile=="GeoParquet-NONE" else "zstd",row_group_size=1000)

def read_profile(path, profile):
    if profile=="GeoJSON":
        fc=json.loads(Path(path).read_bytes())
        return [{"id":int(f["properties"]["id"]),"class":int(f["properties"]["class"]),
                 "geometry":shape(f["geometry"])} for f in fc["features"]]
    if profile=="TopoJSON":return decode_topology(json.loads(Path(path).read_bytes()))
    if profile=="KML":return read_kml(path)
    frame=gpd.read_parquet(path)
    return [{"id":int(i),"class":int(c),"geometry":g}
            for i,c,g in zip(frame["id"].tolist(),frame["class"].tolist(),frame.geometry.tolist())]

def validate(ref, got):
    byid={r["id"]:r for r in got};unique=len(byid)==len(got)
    same_ids=set(byid)=={r["id"] for r in ref}
    equal=0;max_h=0.;max_rel=0.;valid=True;attrs=True
    if not same_ids:return {"passed":False,"same_ids":False,"unique_ids":unique}
    for r in ref:
        a=r["geometry"];b=byid[r["id"]]["geometry"]
        valid=valid and b.is_valid and not b.is_empty
        attrs=attrs and r["class"]==byid[r["id"]]["class"]
        equal+=int(a.equals(b))
        max_h=max(max_h,a.hausdorff_distance(b))
        max_rel=max(max_rel,abs(a.area-b.area)/a.area)
    passed=unique and same_ids and valid and attrs and max_h<=1e-12 and max_rel<=1e-8
    return {"passed":bool(passed),"feature_count":len(got),"unique_ids":unique,
        "same_ids":same_ids,"attributes_equal":bool(attrs),"all_valid_nonempty":bool(valid),
        "topologically_equal_count":equal,"max_hausdorff_degrees":max_h,
        "max_relative_area_error":max_rel,"geometric_tolerance_degrees":1e-12}

def timed(fn):
    gc.collect()
    begin=time.perf_counter_ns()
    result=fn()
    return result,(time.perf_counter_ns()-begin)/1e6

def stats(vals):
    return {"median":float(statistics.median(vals)),"q1":float(np.percentile(vals,25)),
            "q3":float(np.percentile(vals,75)),"min":float(min(vals)),"max":float(max(vals))}
def write_csv(path,rows):
    if not rows:return
    keys=list(dict.fromkeys(k for r in rows for k in r))
    with Path(path).open("w",newline="",encoding="utf-8") as f:
        w=csv.DictWriter(f,fieldnames=keys);w.writeheader();w.writerows(rows)

def flatten_refs(g):
    if isinstance(g,int):yield g
    else:
        for v in g:yield from flatten_refs(v)
def arc_stats(t):
    refs=[i for f in t["objects"]["cells"]["geometries"] for i in flatten_refs(f["arcs"])]
    count=collections.Counter(i if i>=0 else ~i for i in refs)
    return {"arcs":len(t["arcs"]),"shared_arcs":sum(n>1 for n in count.values()),
            "arc_references":len(refs),"coordinate_pairs_in_arcs":sum(len(a) for a in t["arcs"]),
            "transform_present":"transform" in t}
def pair_metrics(rows):
    a,b=[shapely.transform(r["geometry"],TO_UTM.transform,interleaved=False) for r in rows]
    srca,srcb=[r["geometry"] for r in rows]
    return {"touches":bool(srca.touches(srcb)),"distance_utm_m":a.distance(b),
        "overlap_area_utm_m2":a.intersection(b).area,
        "shared_boundary_length_utm_m":a.boundary.intersection(b.boundary).length,
        "all_valid":all(r["geometry"].is_valid for r in rows)}
