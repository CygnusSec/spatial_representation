def tile_bounds(z,x,y):
    side=2*MERCATOR_HALF/(1<<z)
    left=-MERCATOR_HALF+x*side;top=MERCATOR_HALF-y*side
    return left,top-side,left+side,top
def tile_indices(b,z):
    side=2*MERCATOR_HALF/(1<<z)
    minx,miny,maxx,maxy=b
    x0=math.floor((minx+MERCATOR_HALF)/side);x1=math.floor((maxx+MERCATOR_HALF)/side)
    y0=math.floor((MERCATOR_HALF-maxy)/side);y1=math.floor((MERCATOR_HALF-miny)/side)
    return [(x,y) for x in range(x0,x1+1) for y in range(y0,y1+1)]
def decode_tiles(entries):
    results=[]
    for info in entries:
        layer=mvt.decode(Path(info["path"]).read_bytes())["cells"]
        unit=(2*MERCATOR_HALF/(1<<info["z"]))/EXTENT
        global_x_offset=info["x"]*EXTENT
        global_y_offset=((1<<info["z"])-info["y"]-1)*EXTENT
        def world_xy(coords):
            converted=coords.copy()
            converted[:,0]=-MERCATOR_HALF+(coords[:,0]+global_x_offset)*unit
            converted[:,1]=-MERCATOR_HALF+(coords[:,1]+global_y_offset)*unit
            return converted
        for f in layer["features"]:
            # mapbox_vector_tile.decode defaults to Cartesian y-up coordinates.
            g=shape(f["geometry"])
            # A canonical global integer grid avoids introducing different
            # floating-point values for the same boundary in adjacent tiles.
            g=shapely.transform(g,world_xy)
            p=f["properties"]
            results.append({"id":int(p["id"]),"class":int(p["class"]),"geometry":g})
    return results

def experiment3(out,n,repeats,zooms):
    rows,_=grid(n)
    projected=[{"id":r["id"],"class":r["class"],"geometry":shapely.transform(r["geometry"],TO_MERC.transform,interleaved=False)} for r in rows]
    geoms=[r["geometry"] for r in projected];tree=STRtree(geoms);byid={r["id"]:r for r in projected}
    b=unary_union(geoms).bounds
    cx=(b[0]+b[2])/2;cy=(b[1]+b[3])/2
    vw=(b[2]-b[0])/4;vh=(b[3]-b[1])/4
    view=box(cx-vw/2,cy-vh/2,cx+vw/2,cy+vh/2)
    relevant={r["id"] for r in projected if r["geometry"].intersection(view).area>0}
