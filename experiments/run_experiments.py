    for z in zooms:
        directory=out/"data"/"e3"/f"z{z}";directory.mkdir(parents=True,exist_ok=True)
        entries=[];start=time.perf_counter_ns()
        for x,y in tile_indices(b,z):
            bounds=tile_bounds(z,x,y);rect=box(*bounds);features=[]
            for idx in tree.query(rect,predicate="intersects"):
                r=projected[int(idx)];clipped=r["geometry"].intersection(rect)
                if clipped.is_empty or clipped.area<=0:continue
                if clipped.geom_type not in ("Polygon","MultiPolygon"):continue
                features.append({"id":r["id"],"properties":{"id":r["id"],"class":r["class"]},"geometry":clipped})
            if not features:continue
            payload=mvt.encode({"name":"cells","features":features},
                default_options={"quantize_bounds":bounds,"extents":EXTENT,"y_coord_down":False})
            path=directory/f"{x}_{y}.pbf";path.write_bytes(payload)
            entries.append({"z":z,"x":x,"y":y,"bounds":bounds,"path":str(path),
                "raw_bytes":len(payload),"gzip6_bytes":len(gzip.compress(payload,compresslevel=6,mtime=0)),
                "input_fragments":len(features)})
        build_ms=(time.perf_counter_ns()-start)/1e6
        selected=[e for e in entries if box(*e["bounds"]).intersection(view).area>0]
        full=decode_tiles(entries);view_decoded=decode_tiles(selected)
        parts=collections.defaultdict(list);attr_ok=True
